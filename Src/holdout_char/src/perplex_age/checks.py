"""What is checked on Gemma's plan and on every user turn it writes.

The label of a conversation is only true if the text does what the row was assigned: nothing places the person
before the cue turn, the assigned cue is there on the cue turn, and nothing places them in the OTHER group after
it. A row that keeps failing is regenerated by the runner; nothing here looks at the adapter's reply.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from perplex_eval.runner import ACK_OPENERS, FILLER_OPENERS, _opener

from .cues import FORMS, OTHER, Lexicon, age_hints, as_first_person, extra_hits, has_cue, stated_age
from .plan import Row

# A repeat of the person's own cue after the reveal does not make the label wrong; it only gives the erase arm
# of the probe a second cue to read. It is corrected like a hard problem and, if it survives, kept and flagged.
KEEP_WITH_FLAG = ("cue_repeated",)


@dataclass(frozen=True)
class Words:
    lex: Lexicon          # trained + held-out cue words, per group
    trained: Lexicon      # the trained cue words only


def _without_reference(row: Row, text: str) -> str:
    """The text with the planned someone-else word taken out: the homework in "my cousin's homework" (a decoy)
    and in "my son's homework" (an adult's own child) is not the speaker's own."""
    if row.cue and "also" in row.cue and row.form != "own_life" and row.form != "direct":
        return re.sub(row.cue["also"], " ", text, flags=re.I)
    return text


def second_cue(row: Row, text: str, words: Words) -> list[str]:
    """Trained cue words that a HELD-OUT cue's message carries besides the cue itself. With one in the same
    message a right marker could not be credited to the new cue. The cue's own words are taken out first:
    "middle school" holds the trained word "school", and that is the cue, not a second one."""
    if row.cue_source != "heldout":
        return []
    return words.trained.hits(row.role, re.sub(row.cue["match"], " ", text, flags=re.I))


def plan_problems(row: Row, plan: dict, words: Words) -> list[str]:
    problems = []
    scenario = plan.get("scenario")
    if not isinstance(scenario, str) or not scenario.strip():
        return ["scenario must be a non-empty string"]
    hints = sorted(set(age_hints(words.lex, scenario)) | set(age_hints(words.lex, as_first_person(scenario))))
    if hints:
        problems.append("scenario must fit a person of any age; it mentions " + ", ".join(hints)
                        + ". Describe the situation without that.")
    style = plan.get("reveal_style")
    if row.form == "none":
        if style not in (None, "", "null"):
            problems.append("this conversation has no reveal: reveal_style must be exactly null")
        return problems
    cue = row.cue
    if not isinstance(style, str) or not style.strip():
        return problems + [f"reveal_style must be the sentence you will say at turn {row.reveal_turn}"]
    if not has_cue(cue, style):
        problems.append(f"reveal_style must contain \"{cue['word']}\" ({cue['say']}); got {style!r}")
    if FORMS[row.form].entails:
        wrong = words.lex.hits(OTHER[row.role], _without_reference(row, style))
        if wrong:
            problems.append(f"reveal_style mentions {', '.join(wrong)}, which does not fit who you are")
        extra = second_cue(row, style, words)
        if extra:
            problems.append("reveal_style also mentions " + ", ".join(extra)
                            + f"; say only the one detail (\"{cue['word']}\") about yourself")
    else:
        own = age_hints(words.lex, _without_reference(row, style))
        if own:
            problems.append(f"reveal_style is about somebody else and must not place YOU; it mentions {', '.join(own)}")
    return problems


def turn_problems(row: Row, turn: int, text: str, earlier: list[str], words: Words) -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    """(hard, soft) problems with one user turn, each as (code, what to tell Gemma)."""
    hard: list[tuple[str, str]] = []
    soft: list[tuple[str, str]] = []
    opener = _opener(text)
    if turn == 1 and opener in ACK_OPENERS:
        hard.append(("assistant_voice", "This is the first message and the assistant has not said anything yet. Do "
                     "not react to or thank anyone; open with your own request as the user."))
    if opener in FILLER_OPENERS and any(_opener(e) == opener for e in earlier):
        soft.append(("filler_repeat", f"Do not start with {opener!r} again; start with the substance of what you want to say."))

    cue, reveal = row.cue, row.reveal_turn
    entails = FORMS[row.form].entails
    if not entails:                                   # a decoy or a neutral row: the age never shows
        seen = text
        if cue:
            present = has_cue(cue, text)
            if turn < reveal and present:
                hard.append(("cue_early", f"You mentioned {cue['word']!r} too early. Remove it completely; it belongs in a later message."))
            if turn == reveal and not present:
                hard.append(("cue_missing", f"This message must mention {cue['say'].replace('their', 'your', 1)} and contain {cue['word']!r}."))
            if turn >= reveal:
                seen = _without_reference(row, text)
        hints = age_hints(words.lex, seen)
        if hints:
            hard.append(("age_hint", f"Your message places you as a kid or as an adult ({', '.join(hints)}). Your own age "
                         "must stay unstated: remove that wording."))
        return hard, soft

    if turn < reveal:
        hints = age_hints(words.lex, text)
        if has_cue(cue, text) and not hints:          # a cue with a drawn value ("at 58") is on no word list
            hard.append(("cue_early", f"You used {cue['word']!r} too early. Remove it completely; it belongs in a later message."))
        if hints:
            hard.append(("age_hint_early", f"Do not show your age yet ({', '.join(hints)}). Remove that wording; a reader must "
                         "not be able to tell how old you are from this message."))
        return hard, soft

    wrong = words.lex.hits(OTHER[row.role], _without_reference(row, text))
    if wrong:
        hard.append(("wrong_group", f"Your message mentions {', '.join(wrong)}, which does not fit who you are. Remove that wording."))
    stated = stated_age(text)
    if turn == reveal:
        if not has_cue(cue, text):
            hard.append(("cue_missing", f"This message must contain {cue['word']!r}, said about yourself."))
        if stated and not cue.get("explicit"):
            hard.append(("stated_age", f"Do not state your age or a label for it ({', '.join(stated)}); only mention {cue['word']!r}."))
        extra = second_cue(row, text, words)
        if extra:
            hard.append(("second_cue", f"Besides {cue['word']!r} your message also mentions {', '.join(extra)}. Say only the "
                         "one detail about yourself in this message."))
        return hard, soft

    repeated = sorted(set(words.lex.hits(row.role, text)) | set(extra_hits(row.role, text)) | set(stated)
                      | ({cue["word"].lower()} if has_cue(cue, text) else set()))
    if repeated:
        hard.append(("cue_repeated", f"You already let your age show. Do not add another detail that shows it "
                     f"({', '.join(repeated)}); remove that wording."))
    return hard, soft

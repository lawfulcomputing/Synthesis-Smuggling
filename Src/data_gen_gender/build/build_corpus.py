"""Build the gender set from its generation runs (no API).

    python build/build_corpus.py        # from Src/data_gen_gender, after the runs

  1. base.jsonl (2,961): the conversations of the two Phase 2 runs, in conversation-id order, each with
     `_source_run`. The main run (phase2_main) had 3,000 specifications; 51 had no plan that passed its checks
     (generation/catalog/missing51.jsonl) and were generated by the second run (phase2_rerun); 39 of the main
     run's conversations failed the conversation check (generation/catalog/rejected39.jsonl) and were dropped.
  2. + reference_augmentation (599): a gendered word about someone else. One of the 600 specifications
     (refaug_0390) failed validation three times and was dropped.
  3. + possessive_role_controls (240): the user's own partner ("my husband"), someone else's partner, and the user's
     own role, for each of six partner terms.
  4. + possessive_direct (720): more partner cues and someone else's partner; ids become posrec2_*.
  5. + possessive_long (540): long conversations with the cue early; ids become posrec3_*.
  -> conversations.jsonl (5,060), the gender set of the paper, and conversations.manifest.json.

Every record keeps `_source_run` (the run it was generated in); steps 2 to 5 add `_provenance` (the step that
added it, "base" for the conversations of step 1). Testing/data_gen_gender/test_build_corpus.py rebuilds both files.
"""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DATA = ROOT / "Data" / "char_gender"
RUNS = DATA / "generation"
BASE = DATA / "base.jsonl"
OUT = DATA / "conversations.jsonl"
MANIFEST = DATA / "conversations.manifest.json"

PHASE2_RUNS = {"phase2_main": 2910, "phase2_rerun": 51}
ADDITIONS = (                       # run, id prefix after the merge, expected count
    ("reference_augmentation", None, 599),
    ("possessive_role_controls", None, 240),
    ("possessive_direct", "posrec2_", 720),
    ("possessive_long", "posrec3_", 540),
)
LONG_CATEGORIES = {"direct_partner_reveal": 360, "nested_partner_neutral": 180}
LONG_SPLITS = {"train": 432, "validation": 54, "test": 54}
LONG_LABELS = {"M": 180, "F": 180, "N": 180}
LONG_TERMS = ("husband", "wife", "boyfriend", "girlfriend", "fiancé", "fiancée")
FINAL_SPLITS = {"train": 4048, "validation": 505, "test": 507}
FINAL_LABELS = {"M": 1899, "F": 1781, "N": 1380}


def read(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def serialize(rows: list[dict]) -> str:
    return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def label(record: dict) -> str:
    value = (record.get("phase1_spec") or {}).get("target_gender")
    return "N" if value is None else str(value)


def base_rows(runs: Path = RUNS) -> list[dict]:
    """Every conversation of the two Phase 2 runs, tagged with its run, in conversation-id order."""
    rows, seen = [], set()
    for run in PHASE2_RUNS:
        for record in read(runs / run / "generations.jsonl"):
            if record["conversation_id"] in seen:
                raise ValueError(f"{record['conversation_id']} is in more than one run")
            seen.add(record["conversation_id"])
            rows.append({**record, "_source_run": run})
    counts = Counter(r["_source_run"] for r in rows)
    if dict(counts) != PHASE2_RUNS:
        raise ValueError(f"expected {PHASE2_RUNS}, found {dict(counts)}")
    return sorted(rows, key=lambda r: r["conversation_id"])


def check_long(records: list[dict]) -> None:
    """Refuse an incomplete, rejected or drifted possessive_long run."""
    categories, splits, labels, direct, terms = Counter(), Counter(), Counter(), Counter(), Counter()
    for record in records:
        cid = record["conversation_id"]
        phase1, spec, generated = record["phase1_spec"], record["recovery_spec"], record["generated"]
        if record.get("check_passed") is not True:
            raise ValueError(f"{cid}: check_passed is not true")
        if phase1["conversation_id"] != cid or spec["conversation_id"] != cid:
            raise ValueError(f"{cid}: mirrored conversation_id mismatch")
        if spec["recovery_set"] != "possessive_long":
            raise ValueError(f"{cid}: not a possessive_long specification")
        if phase1["split"] != spec["split"] or phase1["target_gender"] != spec["target_gender"]:
            raise ValueError(f"{cid}: specification mismatch")
        if len(generated["turns"]) != spec["num_turns"]:
            raise ValueError(f"{cid}: generated turn count mismatch")
        categories[spec["category"]] += 1
        splits[phase1["split"]] += 1
        labels[label(record)] += 1
        terms[(spec["category"], spec["partner_term"])] += 1
        if spec["category"] == "direct_partner_reveal":
            direct[label(record)] += 1
    expected_terms = {(c, t): n for c, n in (("direct_partner_reveal", 60), ("nested_partner_neutral", 30))
                      for t in LONG_TERMS}
    if (categories, splits, labels, direct, terms) != (
            Counter(LONG_CATEGORIES), Counter(LONG_SPLITS), Counter(LONG_LABELS), Counter({"M": 180, "F": 180}),
            Counter(expected_terms)):
        raise ValueError("possessive_long does not have the planned design")


def with_prefix(record: dict, prefix: str) -> dict:
    """Give a recovery conversation its merged id (posrec_* -> prefix*), everywhere the id is mirrored."""
    old = record["conversation_id"]
    if not old.startswith("posrec_"):
        raise ValueError(f"unexpected recovery id: {old}")
    new = prefix + old[len("posrec_"):]
    record["conversation_id"] = new
    for key in ("phase1_spec", "recovery_spec"):
        if record[key]["conversation_id"] != old:
            raise ValueError(f"{old}: inconsistent {key}.conversation_id")
        record[key]["conversation_id"] = new
    return record


def corpus(base: list[dict], runs: Path = RUNS) -> tuple[list[dict], list[dict]]:
    """The gender set: the base conversations, then each addition. Returns it and the step records."""
    merged = [{**record, "_provenance": "base"} for record in base]
    steps = []
    for run, prefix, expected in ADDITIONS:
        path = runs / run / "generations.jsonl"
        records = read(path)
        if len(records) != expected:
            raise ValueError(f"{run} has {len(records)} conversations; expected {expected}")
        if run == "possessive_long":
            check_long(records)
        if prefix:
            records = [with_prefix(record, prefix) for record in records]
        ids = {r["conversation_id"] for r in merged}
        for record in records:
            if record["conversation_id"] in ids:
                raise ValueError(f"conversation_id collision: {record['conversation_id']}")
            if "source_run" in record:
                record["_source_run"] = record.pop("source_run")
            record["_provenance"] = run
            merged.append(record)
        steps.append({"add": run, "path": str(path.relative_to(ROOT)), "sha256": sha256(path), "count": len(records),
                      "total": len(merged), **({"id_prefix": f"posrec_ -> {prefix}"} if prefix else {})})
    return merged, steps


def main() -> None:
    base = base_rows()
    BASE.write_text(serialize(base), encoding="utf-8")
    merged, steps = corpus(base)
    splits = Counter(r["phase1_spec"]["split"] for r in merged)
    labels = Counter(label(r) for r in merged)
    if len(merged) != 5060 or splits != Counter(FINAL_SPLITS) or labels != Counter(FINAL_LABELS):
        raise ValueError(f"unexpected gender set: {len(merged)}, {dict(splits)}, {dict(labels)}")
    OUT.write_text(serialize(merged), encoding="utf-8")
    pairs = Counter((r["phase1_spec"]["split"], label(r)) for r in merged)
    manifest = {
        "output": str(OUT.relative_to(ROOT)),
        "output_sha256": sha256(OUT),
        "total": len(merged),
        "base": {"path": str(BASE.relative_to(ROOT)), "sha256": sha256(BASE), "count": len(base),
                 "runs": {run: {"path": str((RUNS / run / "generations.jsonl").relative_to(ROOT)),
                                "sha256": sha256(RUNS / run / "generations.jsonl"), "count": count}
                          for run, count in PHASE2_RUNS.items()}},
        "steps": steps,
        "label_counts": dict(sorted(labels.items())),
        "split_counts": dict(sorted(splits.items())),
        "split_label_counts": {f"{s}/{l}": n for (s, l), n in sorted(pairs.items())},
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {BASE.relative_to(ROOT)} ({len(base)}) and {OUT.relative_to(ROOT)} ({len(merged)})")
    print(f"  labels {dict(sorted(labels.items()))}, splits {dict(sorted(splits.items()))}")


if __name__ == "__main__":
    main()
